#!/usr/bin/env python3
"""Generate sdk/include/branes/synapse/tokenizer/unicode_tables.hpp.

The Llama-3 pre-tokenizer classifies code points as letters (\\p{L}: general
categories Lu Ll Lt Lm Lo), numbers (\\p{N}: Nd Nl No), and whitespace (\\s:
the White_Space property). This script reads UnicodeData.txt for a pinned
Unicode version (15.1.0, the version llama.cpp's unicode-data.cpp was built
from) and writes the letter and number sets as sorted inclusive ranges.

Usage:
  python3 scripts/gen_unicode_tables.py [--ucd UnicodeData.txt] \\
      sdk/include/branes/synapse/tokenizer/unicode_tables.hpp

Without --ucd the file is downloaded from unicode.org.
"""

import argparse
import urllib.request
from pathlib import Path

UNICODE_VERSION = "15.1.0"
UCD_URL = f"https://www.unicode.org/Public/{UNICODE_VERSION}/ucd/UnicodeData.txt"
MAX_CODEPOINT = 0x110000


def categories(text: str) -> list[str]:
    """General category of every code point ('Cn' where unassigned)."""
    cat = ["Cn"] * MAX_CODEPOINT
    first = None
    for line in text.splitlines():
        fields = line.split(";")
        cpt, name, gc = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            first = cpt
            continue
        if name.endswith(", Last>"):
            for c in range(first, cpt + 1):
                cat[c] = gc
            continue
        cat[cpt] = gc
    return cat


def ranges(member: list[bool]) -> list[tuple[int, int]]:
    out = []
    start = None
    for c, m in enumerate(member + [False]):
        if m and start is None:
            start = c
        elif not m and start is not None:
            out.append((start, c - 1))
            start = None
    return out


def emit(name: str, rs: list[tuple[int, int]]) -> str:
    lines = [f"inline constexpr std::array<code_point_range, {len(rs)}> {name}{{{{"]
    for i in range(0, len(rs), 4):
        lines.append("    " + " ".join(f"{{0x{a:05X}, 0x{b:05X}}}," for a, b in rs[i:i + 4]))
    lines.append("}};")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ucd", type=Path, help=f"UnicodeData.txt for Unicode {UNICODE_VERSION}")
    ap.add_argument("output", type=Path)
    args = ap.parse_args()
    text = args.ucd.read_text() if args.ucd else urllib.request.urlopen(UCD_URL).read().decode()
    cat = categories(text)
    letters = ranges([c in ("Lu", "Ll", "Lt", "Lm", "Lo") for c in cat])
    numbers = ranges([c in ("Nd", "Nl", "No") for c in cat])
    header = f"""#pragma once
/// @file unicode_tables.hpp
/// @brief Unicode {UNICODE_VERSION} letter (\\p{{L}}) and number (\\p{{N}}) code point ranges.
///
/// Generated by scripts/gen_unicode_tables.py from UnicodeData.txt; do not
/// edit. Ranges are inclusive, sorted, and disjoint.

#include <array>
#include <cstdint>

namespace branes::synapse::tokenizer::detail {{

struct code_point_range {{
    std::uint32_t first, last;
}};

{emit("letter_ranges", letters)}

{emit("number_ranges", numbers)}

}}  // namespace branes::synapse::tokenizer::detail
"""
    args.output.write_text(header)
    print(f"wrote {args.output}: {len(letters)} letter ranges, {len(numbers)} number ranges")


if __name__ == "__main__":
    main()
